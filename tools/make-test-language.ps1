<#
.SYNOPSIS
  Makes the stretched test language (tag en-XZ, folder values-en-rXZ) from the English strings files.

.DESCRIPTION
  Feature 0.11 of Wave 0. Every English text is rewritten with its vowels marked (a -> a-ring and so on),
  each word lengthened to at least 1.4 times its letters, and the whole text put in square brackets.
  Placeholders (%1$s, %d, %%), escapes (\' \n \uXXXX), entities (&amp;) and tags stay as they are. The
  result is English in every rule (plurals keep the English form), so a screen can be looked at in a
  language 40 percent longer than English before any translation exists, and a text that is not
  bracketed on a screen is a text that did not come from the resources.

  The folder is written for the debug builds only (app/src/debug/res/values-en-rXZ) and is committed.
  A hash of the English files sits in the header of every output file; -Check compares it.

  A second folder is written next to it, app/src/debug/res/values-en: a plain copy of the English texts (only the
  notes are left out; translatable=false texts and the keys the twin overlay app/src/twin/res overrides are not
  copied). It exists because Android prefers a folder that names the language "en" and a region (en-XZ counts as
  close to US English) over the default folder, when the system or the app asks for English: without a region-less
  values-en the whole debug interface would come out in the bracketed language for every English request except
  exactly en-US. Asking for en-XZ still gets the bracketed folder.

  powershell -NoProfile -ExecutionPolicy Bypass -File tools\make-test-language.ps1 [-ResDir d] [-OutDir d] [-EnOutDir d] [-Tag en-XZ] [-Check] [-SelfTest]

  Exit: 0 ok; 1 error; 3 with -Check when an output is missing or stale.
  Runs on Windows PowerShell 5.1 and pwsh 7. This file is ASCII only on purpose (5.1 reads a file
  without a byte order mark as ANSI).
#>
[CmdletBinding()]
param(
    [string]$ResDir = '',
    [string]$OutDir = '',
    [string]$EnOutDir = '',
    [string]$Tag = 'en-XZ',
    [switch]$Check,
    [switch]$SelfTest
)

$ErrorActionPreference = 'Stop'

$script:Root = Split-Path -Parent $PSScriptRoot
if (-not $ResDir) { $ResDir = Join-Path $script:Root 'app/src/main/res' }
$script:Folder = 'values-' + ($Tag -replace '-([A-Za-z]{2})$', '-r$1')
if (-not $OutDir) { $OutDir = Join-Path $script:Root ('app/src/debug/res/' + $script:Folder) }
# The region-less twin folder (values-en) sits beside the stretched one.
if (-not $EnOutDir) { $EnOutDir = Join-Path (Split-Path -Parent $OutDir) ('values-' + ($Tag -replace '-.*$', '')) }
$script:GeneratedMark = 'GENERATED by tools/make-test-language.ps1'

# Bump when the algorithm changes, so every generated file counts as stale.
$script:AlgoVersion = 3
$script:Stretch = 1.4

$script:VowelsPlain = 'aeiouAEIOU'
# a-ring, e-acute, i-circumflex, o-diaeresis, u-diaeresis, then the capitals; written as code points
$script:VowelsMarked = @(0x00E5, 0x00E9, 0x00EE, 0x00F6, 0x00FC, 0x00C5, 0x00C9, 0x00CE, 0x00D6, 0x00DC) | ForEach-Object { [string][char]$_ }

# Text that must stay as it is: a format placeholder, an escape, an entity, a tag.
$script:PlaceholderPattern = '%(?:\d+\$)?[-#+0,(]*\d*(?:\.\d+)?[a-zA-Z%]'
$script:AtomPattern = $script:PlaceholderPattern + '|\\u[0-9a-fA-F]{4}|\\.|&#?\w+;|<[^>]*>'

function Read-Utf8([string]$Path) {
    [System.IO.File]::ReadAllText($Path, (New-Object System.Text.UTF8Encoding($false)))
}

function Write-Utf8Lf([string]$Path, [string]$Text) {
    $dir = Split-Path -Parent $Path
    if ($dir -and -not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    [System.IO.File]::WriteAllText($Path, $Text, (New-Object System.Text.UTF8Encoding($false)))
}

# Length of a text as the strings check counts it: tags 0, a placeholder 2, an escape or entity 1.
function Get-EffLen([string]$Raw) {
    $t = [regex]::Replace($Raw, '<[^>]*>', '')
    $t = [regex]::Replace($t, $script:PlaceholderPattern, { param($m) if ($m.Value -eq '%%') { '%' } else { 'XX' } })
    $t = [regex]::Replace($t, '\\u[0-9a-fA-F]{4}|\\.|&#?\w+;', 'X')
    return $t.Length
}

function Convert-Word([string]$Word) {
    $need = [int][math]::Ceiling($script:Stretch * $Word.Length - 1e-9)
    $sb = New-Object System.Text.StringBuilder
    $marked = New-Object 'System.Collections.Generic.List[string]'
    foreach ($ch in $Word.ToCharArray()) {
        $i = $script:VowelsPlain.IndexOf($ch)
        if ($i -ge 0) {
            $m = $script:VowelsMarked[$i]
            [void]$sb.Append($m)
            $marked.Add($m)
        } else {
            [void]$sb.Append($ch)
        }
    }
    $k = 0
    while ($sb.Length -lt $need) {
        if ($marked.Count -gt 0) {
            [void]$sb.Append($marked[$k % $marked.Count])
            $k++
        } else {
            [void]$sb.Append('x')
        }
    }
    return $sb.ToString()
}

function Convert-Run([string]$Run) {
    return [regex]::Replace($Run, '\p{L}+', { param($m) Convert-Word $m.Value })
}

# One text (the raw XML inside a string or an item) becomes its stretched twin.
function Convert-Inner([string]$Inner) {
    $sb = New-Object System.Text.StringBuilder
    $pos = 0
    foreach ($m in [regex]::Matches($Inner, $script:AtomPattern)) {
        if ($m.Index -gt $pos) { [void]$sb.Append((Convert-Run $Inner.Substring($pos, $m.Index - $pos))) }
        [void]$sb.Append($m.Value)
        $pos = $m.Index + $m.Length
    }
    if ($pos -lt $Inner.Length) { [void]$sb.Append((Convert-Run $Inner.Substring($pos))) }
    $body = $sb.ToString()
    # A text with hardly any letters ("%1$d/%2$d") is padded so that it is still 1.4 times as long.
    $want = [int][math]::Ceiling($script:Stretch * (Get-EffLen $Inner) - 1e-9)
    while (((Get-EffLen $body) + 2) -lt $want) { $body += 'x' }
    return '[' + $body + ']'
}

# The English files in ordinal (code point) order. Sort-Object compares by culture, and the culture order differs
# between Windows PowerShell 5.1 and pwsh 7 on Linux ('.' and '_'), which changed the hash and failed -Check in CI.
function Get-EnglishFiles([string]$Dir) {
    $valuesDir = Join-Path $Dir 'values'
    if (-not (Test-Path -LiteralPath $valuesDir)) { throw "no values folder under $Dir" }
    $files = @(Get-ChildItem -LiteralPath $valuesDir -File -Filter 'strings*.xml')
    $names = [string[]]@($files | ForEach-Object { $_.Name })
    [Array]::Sort($names, [StringComparer]::Ordinal)
    $sorted = New-Object 'System.Collections.Generic.List[object]'
    foreach ($n in $names) {
        foreach ($f in $files) { if ($f.Name -ceq $n) { $sorted.Add($f); break } }
    }
    return $sorted.ToArray()
}

# The text names the twin overlay (app/src/twin/res) overrides: the values-en copy must not hide them.
function Get-TwinNames([string]$Dir) {
    $twinRes = Join-Path (Join-Path (Split-Path -Parent (Split-Path -Parent $Dir)) 'twin') 'res'
    $found = New-Object 'System.Collections.Generic.List[string]'
    if (Test-Path -LiteralPath $twinRes) {
        foreach ($d in @(Get-ChildItem -LiteralPath $twinRes -Directory -Filter 'values*')) {
            foreach ($f in @(Get-ChildItem -LiteralPath $d.FullName -File -Filter 'strings*.xml')) {
                $text = [regex]::Replace((Read-Utf8 $f.FullName), '(?s)<!--.*?-->', '')
                foreach ($m in [regex]::Matches($text, '<(?:string|plurals)\s[^>]*?name\s*=\s*"([^"]+)"')) {
                    if (-not $found.Contains($m.Groups[1].Value)) { $found.Add($m.Groups[1].Value) }
                }
            }
        }
    }
    $arr = $found.ToArray()
    [Array]::Sort($arr, [StringComparer]::Ordinal)
    return $arr
}

function Get-SourceHash([string]$Dir) {
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.Append("algo=$($script:AlgoVersion)`n")
    [void]$sb.Append('twin=' + ((Get-TwinNames $Dir) -join ',') + "`n")
    foreach ($f in (Get-EnglishFiles $Dir)) {
        $text = (Read-Utf8 $f.FullName).Replace("`r`n", "`n").Replace("`r", "`n")
        [void]$sb.Append($f.Name + "`n" + $text + "`n")
    }
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try {
        $bytes = $sha.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($sb.ToString()))
    } finally {
        $sha.Dispose()
    }
    $hex = -join ($bytes | ForEach-Object { $_.ToString('x2') })
    return $hex.Substring(0, 32)
}

function Convert-StringsFile([string]$Text, [string]$Hash) {
    $clean = [regex]::Replace($Text, '(?s)<!--.*?-->', '')
    $out = New-Object System.Text.StringBuilder
    [void]$out.Append("<?xml version=`"1.0`" encoding=`"utf-8`"?>`n<resources>`n")
    [void]$out.Append("    <!-- $($script:GeneratedMark); do not edit; debug builds only | source-hash: $Hash -->`n")
    foreach ($m in [regex]::Matches($clean, '(?s)<(string|plurals)(?=[\s>])([^>]*)>(.*?)</\1>')) {
        $kind = $m.Groups[1].Value
        $attrs = $m.Groups[2].Value
        $inner = $m.Groups[3].Value
        if ($attrs -match 'translatable\s*=\s*"false"') { continue }
        if ($kind -eq 'string') {
            [void]$out.Append('    <string' + $attrs + '>' + (Convert-Inner $inner) + "</string>`n")
        } else {
            [void]$out.Append('    <plurals' + $attrs + ">`n")
            foreach ($im in [regex]::Matches($inner, '(?s)<item\b([^>]*)>(.*?)</item>')) {
                [void]$out.Append('        <item' + $im.Groups[1].Value + '>' + (Convert-Inner $im.Groups[2].Value) + "</item>`n")
            }
            [void]$out.Append("    </plurals>`n")
        }
    }
    [void]$out.Append("</resources>`n")
    return $out.ToString()
}

# The region-less English folder: the English texts as they are (notes left out), minus the texts that must not be
# copied (translatable=false, and the names in $Skip that an overlay of the twin app overrides).
function Convert-EnglishCopy([string]$Text, [string]$Hash, [string[]]$Skip) {
    $clean = [regex]::Replace($Text, '(?s)<!--.*?-->', '')
    $out = New-Object System.Text.StringBuilder
    [void]$out.Append("<?xml version=`"1.0`" encoding=`"utf-8`"?>`n<resources>`n")
    [void]$out.Append("    <!-- $($script:GeneratedMark); do not edit; debug builds only; plain English copy | source-hash: $Hash -->`n")
    foreach ($m in [regex]::Matches($clean, '(?s)<(string|plurals)(?=[\s>])([^>]*)>(.*?)</\1>')) {
        $kind = $m.Groups[1].Value
        $attrs = $m.Groups[2].Value
        if ($attrs -match 'translatable\s*=\s*"false"') { continue }
        $nm = [regex]::Match($attrs, 'name\s*=\s*"([^"]+)"')
        if ($nm.Success -and ($Skip -ccontains $nm.Groups[1].Value)) { continue }
        [void]$out.Append('    <' + $kind + $attrs + '>' + $m.Groups[3].Value + '</' + $kind + ">`n")
    }
    [void]$out.Append("</resources>`n")
    return $out.ToString()
}

# Removes the generated strings files of $Out that are not in $Names (a file without our mark is never removed).
function Remove-StaleGenerated([string]$Out, [string[]]$Names) {
    if (-not (Test-Path -LiteralPath $Out)) { return }
    foreach ($old in (Get-ChildItem -LiteralPath $Out -File -Filter 'strings*.xml')) {
        if ($Names -contains $old.Name) { continue }
        $head = Read-Utf8 $old.FullName
        if ($head.Length -gt 400) { $head = $head.Substring(0, 400) }
        if ($head.Contains($script:GeneratedMark)) { Remove-Item -LiteralPath $old.FullName -Force }
    }
}

function Invoke-Generate([string]$Dir, [string]$Out, [string]$EnOut) {
    $hash = Get-SourceHash $Dir
    $skip = [string[]]@(Get-TwinNames $Dir)
    $names = @()
    foreach ($f in (Get-EnglishFiles $Dir)) {
        $names += $f.Name
        $raw = Read-Utf8 $f.FullName
        Write-Utf8Lf (Join-Path $Out $f.Name) (Convert-StringsFile $raw $hash)
        Write-Utf8Lf (Join-Path $EnOut $f.Name) (Convert-EnglishCopy $raw $hash $skip)
    }
    Remove-StaleGenerated $Out $names
    Remove-StaleGenerated $EnOut $names
    return $names.Count
}

# Returns $null when one output folder matches the English files, else a sentence that says what is wrong.
function Test-FreshFolder([string]$Folder, [string]$Hash, [string[]]$Names) {
    $leaf = Split-Path -Leaf $Folder
    foreach ($n in $Names) {
        $p = Join-Path $Folder $n
        if (-not (Test-Path -LiteralPath $p)) { return "missing $n in $leaf" }
        $head = (Read-Utf8 $p)
        if ($head.Length -gt 400) { $head = $head.Substring(0, 400) }
        if ($head -notmatch ('source-hash: ' + $Hash + '\b')) { return "stale $n in $leaf" }
    }
    foreach ($old in (Get-ChildItem -LiteralPath $Folder -File -Filter 'strings*.xml')) {
        if ($Names -notcontains $old.Name) { return "extra $($old.Name) in $leaf" }
    }
    return $null
}

# Returns $null when both outputs match the English files, else a sentence that says what is wrong.
function Test-Fresh([string]$Dir, [string]$Out, [string]$EnOut) {
    $hash = Get-SourceHash $Dir
    $names = [string[]]@(Get-EnglishFiles $Dir | ForEach-Object { $_.Name })
    foreach ($folder in @($Out, $EnOut)) {
        if (-not (Test-Path -LiteralPath $folder)) { return "missing folder $(Split-Path -Leaf $folder)" }
        $problem = Test-FreshFolder $folder $hash $names
        if ($problem) { return $problem }
    }
    return $null
}

function Invoke-SelfTest {
    function Assert-That([bool]$Cond, [string]$Name) {
        if ($Cond) { Write-Host "ok   $Name" } else { Write-Host "FAIL $Name"; $script:selfFailures++ }
    }
    $script:selfFailures = 0
    $a = [string][char]0x00E5

    Assert-That ((Convert-Word 'Cat') -ceq ('C' + $a + 't' + $a + $a)) 'vowel marked and lengthened (Cat)'
    Assert-That ((Convert-Word 'by') -ceq 'byx') 'a word without vowel gets x'
    Assert-That ((Convert-Word 'a') -ceq ($a + $a)) 'a one-letter word is doubled'

    $inner = 'Hello %1$s, you have %2$d new messages\n(don\''t panic) &amp; <b>go</b> 100%%'
    $res = Convert-Inner $inner
    $phIn = ([regex]::Matches($inner, $script:PlaceholderPattern) | ForEach-Object { $_.Value }) -join '|'
    $phOut = ([regex]::Matches($res, $script:PlaceholderPattern) | ForEach-Object { $_.Value }) -join '|'
    Assert-That ($phIn -ceq $phOut) 'placeholders kept in order'
    Assert-That ($res.StartsWith('[') -and $res.EndsWith(']')) 'text is bracketed'
    Assert-That ($res.Contains('\n') -and $res.Contains('\''') -and $res.Contains('&amp;') -and $res.Contains('<b>') -and $res.Contains('</b>')) 'escapes, entity and tags kept'
    Assert-That (([regex]::Matches($res, "(?<!\\)'")).Count -eq 0) 'no unescaped apostrophe appears'
    Assert-That ((Get-EffLen $res) -ge [int][math]::Floor($script:Stretch * (Get-EffLen $inner))) 'at least 1.4 times as long'

    $short = Convert-Inner '%1$d/%2$d'
    Assert-That ((Get-EffLen $short) -ge [int][math]::Floor($script:Stretch * (Get-EffLen '%1$d/%2$d'))) 'a text with no letters is long enough'
    $pad = Convert-Inner '%d'
    Assert-That ((Get-EffLen $pad) -ge [int][math]::Floor($script:Stretch * 2)) 'a bare placeholder is long enough'
    Assert-That ($short.StartsWith('[%1$d/%2$d')) 'padding comes after the placeholders'

    $tmp = Join-Path ([System.IO.Path]::GetTempPath()) ('mtl-selftest-' + [guid]::NewGuid().ToString('N'))
    try {
        $res1 = Join-Path $tmp 'src/main/res'
        $out1 = Join-Path $tmp 'src/debug/res/values-en-rXZ'
        $en1 = Join-Path $tmp 'src/debug/res/values-en'
        $twin1 = Join-Path $tmp 'src/twin/res/values'
        $valuesDir1 = Join-Path $res1 'values'
        New-Item -ItemType Directory -Path $valuesDir1 -Force | Out-Null
        New-Item -ItemType Directory -Path $twin1 -Force | Out-Null
        $xml = @'
<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- t: a note -->
    <string name="a_one">Hello world</string>
    <string name="a_two" translatable="false">Keep</string>
    <string name="app_name">Agiri</string>
    <plurals name="a_many">
        <item quantity="one">%1$d bot</item>
        <item quantity="other">%1$d bots</item>
    </plurals>
</resources>
'@
        $twinXml = @'
<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- t: the twin | kind: title -->
    <string name="app_name">Agiri Test</string>
</resources>
'@
        Write-Utf8Lf (Join-Path $valuesDir1 'strings_test.xml') $xml
        Write-Utf8Lf (Join-Path $twin1 'strings_build.xml') $twinXml
        $n = Invoke-Generate $res1 $out1 $en1
        Assert-That ($n -eq 1) 'one file generated'
        $gen = Read-Utf8 (Join-Path $out1 'strings_test.xml')
        Assert-That ($gen -match 'name="a_one">\[') 'string generated'
        Assert-That ($gen -notmatch 'a_two') 'translatable=false skipped'
        Assert-That ($gen -match 'quantity="one">\[%1\$d ') 'plural items generated'
        Assert-That ($gen -notmatch '<!-- t:') 'notes are not copied'
        $enGen = Read-Utf8 (Join-Path $en1 'strings_test.xml')
        Assert-That ($enGen -match 'name="a_one">Hello world</string>') 'values-en holds the plain English text'
        Assert-That ($enGen -match 'quantity="other">%1\$d bots</item>') 'values-en keeps the plural items as they are'
        Assert-That ($enGen -notmatch 'a_two') 'values-en skips translatable=false'
        Assert-That ($enGen -notmatch 'app_name') 'values-en skips the names the twin overlay overrides'
        Assert-That ($enGen -notmatch '<!-- t:') 'values-en has no notes'
        $fresh = Test-Fresh $res1 $out1 $en1
        Assert-That ($null -eq $fresh) 'fresh output is accepted'
        Remove-Item -LiteralPath (Join-Path $en1 'strings_test.xml') -Force
        Assert-That ($null -ne (Test-Fresh $res1 $out1 $en1)) 'a missing values-en file is reported'
        [void](Invoke-Generate $res1 $out1 $en1)
        Write-Utf8Lf (Join-Path $valuesDir1 'strings_test.xml') ($xml.Replace('Hello world', 'Hello there'))
        Assert-That ($null -ne (Test-Fresh $res1 $out1 $en1)) 'changed English is stale'
        Write-Utf8Lf (Join-Path $valuesDir1 'strings_test.xml') ($xml.Replace("`n", "`r`n"))
        Assert-That ($null -eq (Test-Fresh $res1 $out1 $en1)) 'line endings do not make it stale'
        Write-Utf8Lf (Join-Path $twin1 'strings_build.xml') ($twinXml.Replace('app_name', 'other_name'))
        Assert-That ($null -ne (Test-Fresh $res1 $out1 $en1)) 'a change of the twin overlay names is stale'
        Write-Utf8Lf (Join-Path $twin1 'strings_build.xml') $twinXml

        # The order of the files must not depend on the culture: strings.xml sorts before strings_a.xml by code point.
        Write-Utf8Lf (Join-Path $valuesDir1 'strings.xml') $xml
        Write-Utf8Lf (Join-Path $valuesDir1 'strings_a.xml') $xml
        $order = (Get-EnglishFiles $res1 | ForEach-Object { $_.Name }) -join ','
        Assert-That ($order -ceq 'strings.xml,strings_a.xml,strings_test.xml') 'English files are in ordinal order (strings.xml first)'
    } finally {
        if (Test-Path -LiteralPath $tmp) { Remove-Item -LiteralPath $tmp -Recurse -Force }
    }
    if ($script:selfFailures -gt 0) { Write-Host "make-test-language: self test FAILED ($($script:selfFailures))"; return 1 }
    Write-Host 'make-test-language: self test ok'
    return 0
}

try {
    if ($SelfTest) {
        $code = Invoke-SelfTest
        exit $code
    }
    if ($Check) {
        if (-not (Test-Path -LiteralPath $OutDir)) {
            Write-Host "make-test-language: $($script:Folder) is missing. Run: powershell -NoProfile -ExecutionPolicy Bypass -File tools\make-test-language.ps1"
            exit 3
        }
        $problem = Test-Fresh $ResDir $OutDir $EnOutDir
        if ($problem) {
            Write-Host "make-test-language: stale ($problem). Run: powershell -NoProfile -ExecutionPolicy Bypass -File tools\make-test-language.ps1"
            exit 3
        }
        Write-Host 'make-test-language: up to date'
        exit 0
    }
    $count = Invoke-Generate $ResDir $OutDir $EnOutDir
    Write-Host "make-test-language: wrote $count files to $OutDir and $EnOutDir"
    exit 0
} catch {
    Write-Host ('make-test-language: ' + $_.Exception.Message)
    exit 1
}
