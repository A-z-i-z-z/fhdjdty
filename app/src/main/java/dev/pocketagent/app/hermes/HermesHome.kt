import dev.pocketagent.app.util.FileUtil
import java.io.File
import java.io.RandomAccessFile

/** The files of HERMES_HOME the app lets the user read and edit. CONFIG is read-only: the app regenerates it on every start. */
enum class HermesDoc { SOUL, MEMORY, USER, CONFIG }

/** One skill. [path] is relative to `<HERMES_HOME>/skills`, with `/` separators, e.g. `research/arxiv/SKILL.md`. */
data class SkillInfo(val name: String, val description: String, val category: String, val path: String)

enum class LogKind { APP, RUNTIME, API }

/**
 * Hermes's user-visible files, read and written straight from the rootfs directory (it is plain files in the app's data dir).
 * Every write is atomic and keeps the previous version as `<file>.bak`. Reads and writes touch the disk: call off the main thread.
 *
 * Memory files (`memories/MEMORY.md`, `memories/USER.md`) hold entries separated by [MemoryFormat.ENTRY_DELIMITER] and Hermes
 * enforces character budgets on them ([MemoryFormat.MEMORY_LIMIT], [MemoryFormat.USER_LIMIT]); the app does not enforce them
 * on write (Hermes will refuse to add to an over-budget file), but the UI can show the budget.
 */
class HermesHome internal constructor(
    private val home: File,
    private val appLog: File,
    private val runtimeLog: File,
) {
    constructor(paths: Paths) : this(paths.hermesHome, File(paths.logs, "app.log"), paths.runtimeLog)

    private val skillsDir get() = File(home, "skills")

    private fun file(doc: HermesDoc): File = when (doc) {
        HermesDoc.SOUL -> File(home, "SOUL.md")
        HermesDoc.MEMORY -> File(File(home, "memories"), "MEMORY.md")
        HermesDoc.USER -> File(File(home, "memories"), "USER.md")
        HermesDoc.CONFIG -> File(home, "config.yaml")
    }

    /** The guest-side path, shown in the UI. */
    private fun guestPath(doc: HermesDoc): String = when (doc) {
        HermesDoc.SOUL -> "/root/.hermes/SOUL.md"
        HermesDoc.MEMORY -> "/root/.hermes/memories/MEMORY.md"
        HermesDoc.USER -> "/root/.hermes/memories/USER.md"
        HermesDoc.CONFIG -> "/root/.hermes/config.yaml"
    }

    /** The file's text, or null when it does not exist (yet). */
    fun read(doc: HermesDoc): String? = Fs.readTextOrNull(file(doc))

    /** Replaces the file (creating it and its directory). Throws [UnsupportedOperationException] for CONFIG. */
    fun write(doc: HermesDoc, text: String) {
        if (doc == HermesDoc.CONFIG) throw UnsupportedOperationException("config.yaml is regenerated by the app on every start and cannot be edited")
        Fs.writeAtomicWithBackup(file(doc), text)
    }

    /** Path inside the guest plus size, e.g. "/root/.hermes/SOUL.md (1.2 KiB)" or "/root/.hermes/memories/USER.md (not created yet)". */
    fun docInfo(doc: HermesDoc): String {
        val f = file(doc)
        return guestPath(doc) + if (f.isFile) " (${formatSize(f.length())})" else " (not created yet)"
    }

    // ---- skills ---------------------------------------------------------------------------------------------------

    /** Every `SKILL.md` below `skills/` (up to 5 levels deep), sorted by category then name. A broken file still lists, by directory name. */
    fun listSkills(): List<SkillInfo> {
        val root = skillsDir
        if (!root.isDirectory) return emptyList()
        val out = ArrayList<SkillInfo>()
        fun walk(d: File, depth: Int) {
            val kids = d.listFiles() ?: return
            for (k in kids.sortedBy { it.name }) {
                if (out.size >= 1000) return
                if (k.name.startsWith(".")) continue
                if (k.isDirectory && depth < 5) walk(k, depth + 1)
                else if (k.isFile && k.name == "SKILL.md") {
                    val rel = k.relativeTo(root).path.replace(File.separatorChar, '/')
                    val dirName = k.parentFile?.name ?: rel
                    val parts = rel.split('/')
                    val category = if (parts.size >= 3) parts.subList(0, parts.size - 2).joinToString("/") else ""
                    val text = try { k.bufferedReader(Charsets.UTF_8).use { r -> CharArray(8192).let { b -> String(b, 0, maxOf(0, r.read(b))) } } } catch (_: Exception) { "" }
                    val fm = SkillParser.parse(text)
                    out += SkillInfo(
                        name = fm.name?.takeIf { it.isNotBlank() } ?: dirName,
                        description = fm.description.orEmpty(),
                        category = category, path = rel,
                    )
                }
            }
        }
        walk(root, 0)
        return out.sortedWith(compareBy({ it.category.lowercase() }, { it.name.lowercase() }))
    }

    /** The text of a skill file ([path] as in [SkillInfo.path]); throws when the path leaves `skills/` or the file is missing. */
    fun readSkill(path: String): String {
        val f = resolveSkill(path)
        if (!f.isFile) throw java.io.FileNotFoundException("no such skill file: $path")
        if (f.length() > MAX_SKILL_BYTES) throw java.io.IOException("skill file is larger than ${MAX_SKILL_BYTES / 1024} KiB")
        return f.readText(Charsets.UTF_8)
    }

    /** Saves a skill file (may create a new `<category>/<name>/SKILL.md`), keeping a `.bak` of the old version. */
    fun writeSkill(path: String, text: String) {
        val f = resolveSkill(path)
        if (text.length > MAX_SKILL_BYTES) throw java.io.IOException("skill text is larger than ${MAX_SKILL_BYTES / 1024} KiB")
        Fs.writeAtomicWithBackup(f, text)
    }

    /**
     * Creates `skills/<category>/<name>/SKILL.md` from [SkillTemplate] (the front matter Hermes's own skills have) and returns it.
     * [category] may be empty (the skill then sits directly below `skills/`). Throws [IllegalArgumentException] with a short reason
     * for a bad name or category and [java.io.IOException] when a skill with that name already exists.
     */
    fun createSkill(category: String, name: String, description: String): SkillInfo {
        val cat = category.trim()
        val skillName = name.trim()
        require(SkillTemplate.isValidName(skillName)) { "invalid skill name" }
        require(cat.isEmpty() || (SkillTemplate.isValidName(cat) && cat !in SkillTemplate.RESERVED_FOLDERS)) { "invalid category" }
        require(skillName !in SkillTemplate.RESERVED_FOLDERS) { "invalid skill name" }
        val rel = (if (cat.isEmpty()) "" else "$cat/") + "$skillName/SKILL.md"
        val f = resolveSkill(rel)                                   // also checks that nothing escapes skills/
        if (cat.isNotEmpty() && File(skillsDir, "$cat/SKILL.md").exists()) throw java.io.IOException("the category \"$cat\" is itself a skill")
        if (f.exists() || f.parentFile?.exists() == true) throw java.io.IOException("a skill named \"$skillName\" already exists")
        val desc = description.trim().replace(Regex("\\s+"), " ").take(SkillTemplate.MAX_DESCRIPTION)
        Fs.writeAtomic(f, SkillTemplate.render(skillName, desc))
        return SkillInfo(skillName, desc, cat, rel)
    }

    /**
     * Deletes the whole folder of the skill whose `SKILL.md` is at [path] (as in [SkillInfo.path]), then its category folder when that
     * is left empty. Refuses anything that is not a `<...>/SKILL.md` below `skills/`, a folder that is a symbolic link, and a
     * folder that holds another skill. Throws [IllegalArgumentException] / [java.io.IOException].
     */
    fun deleteSkill(path: String) {
        val f = resolveSkill(path)
        require(f.name == "SKILL.md" && path.replace('\\', '/').contains('/')) { "not a skill file" }
        val dir = f.parentFile ?: throw IllegalArgumentException("not a skill file")
        val root = skillsDir.canonicalFile
        val canonDir = dir.canonicalFile
        require(canonDir.path.startsWith(root.path + File.separator) && canonDir != root) { "skill folder escapes the skills directory" }
        if (java.nio.file.Files.isSymbolicLink(dir.toPath())) throw java.io.IOException("the skill folder is a symbolic link")
        if (!dir.isDirectory) throw java.io.FileNotFoundException("no such skill: $path")
        val nested = java.nio.file.Files.walk(dir.toPath(), 8).use { st ->
            st.anyMatch { p -> p.fileName?.toString() == "SKILL.md" && p != f.toPath() }
        }
        if (nested) throw java.io.IOException("this folder also holds other skills; delete them one by one")
        FileUtil.deleteOrThrow(dir)
        val parent = dir.parentFile
        if (parent != null && parent.canonicalFile != root && parent.canonicalFile.path.startsWith(root.path + File.separator) && parent.list()?.isEmpty() == true) {
            parent.delete()
        }
    }

    /** [path] must be a relative `.md` path that stays inside `skills/` (no `..`, no absolute paths, no symlink escape). */
    private fun resolveSkill(path: String): File {
        val clean = path.replace('\\', '/').trim()
        require(clean.isNotEmpty() && !clean.startsWith("/") && clean.endsWith(".md")) { "invalid skill path" }
        require(clean.split('/').none { it == ".." || it == "." || it.isEmpty() }) { "invalid skill path" }
        val root = skillsDir.canonicalFile
        val f = File(root, clean)
        val canon = f.canonicalFile
        require(canon.path.startsWith(root.path + File.separator)) { "skill path escapes the skills directory" }
        return f
    }

    // ---- logs ---------------------------------------------------------------------------------------------------------

    /** The last [maxBytes] of a log (secrets redacted); "" when there is none yet. The API log is the in-memory ring of recent calls. */
    fun tailLog(kind: LogKind, maxBytes: Int = 200_000): String {
        val raw = when (kind) {
            LogKind.APP -> {
                val prev = File(appLog.absoluteFile.parentFile, appLog.name + ".1")
                val cur = tailBytes(appLog, maxBytes)
                if (cur.length < maxBytes && prev.isFile) tailBytes(prev, maxBytes - cur.length) + cur else cur
            }
            LogKind.RUNTIME -> tailBytes(runtimeLog, maxBytes)
            LogKind.API -> ApiLog.snapshot().joinToString("\n").let { if (it.length > maxBytes) it.takeLast(maxBytes) else it }
        }
        return Diag.redactor.redact(raw)
    }

    companion object {
        private const val MAX_SKILL_BYTES = 512 * 1024

        /** Reads at most the last [maxBytes] of [f] and drops a leading partial line. */
        internal fun tailBytes(f: File, maxBytes: Int): String {
            if (!f.isFile || maxBytes <= 0) return ""
            return try {
                RandomAccessFile(f, "r").use { raf ->
                    val len = raf.length()
                    val start = maxOf(0L, len - maxBytes)
                    raf.seek(start)
                    val buf = ByteArray((len - start).toInt())
                    raf.readFully(buf)
                    val s = String(buf, Charsets.UTF_8)
                    if (start > 0) s.substringAfter('\n', s) else s
                }
            } catch (_: Exception) { "" }
        }

        internal fun formatSize(b: Long): String = when {
            b >= 1L shl 20 -> "${b / (1L shl 20)}.${(b % (1L shl 20)) * 10 / (1L shl 20)} MiB"
            b >= 1L shl 10 -> "${b / 1024}.${(b % 1024) * 10 / 1024} KiB"
            else -> "$b B"
        }
    }
}

/** Format facts about Hermes's memory files (tools/memory_tool_store.py in Hermes v0.23.3). */
object MemoryFormat {
    /** Entries are joined with this exact string; keep it intact when editing. */
    const val ENTRY_DELIMITER = "\n§\n"
    /** Default character budgets (config keys memory_char_limit / user_char_limit; the app does not change them). */
    const val MEMORY_LIMIT = 2200
    const val USER_LIMIT = 1375

    fun limitOf(doc: HermesDoc): Int = if (doc == HermesDoc.USER) USER_LIMIT else MEMORY_LIMIT

    /** The entries of a memory file, the way Hermes reads it: split on the delimiter, trimmed, empty ones dropped. */
    fun entries(text: String): List<String> = text.split(ENTRY_DELIMITER).map { it.trim() }.filter { it.isNotEmpty() }

    fun join(entries: List<String>): String = entries.joinToString(ENTRY_DELIMITER)

    /** Hermes's budget counts the joined text (delimiters included). */
    fun usedChars(entries: List<String>): Int = join(entries).length
}

/** Parses the YAML frontmatter at the top of a `SKILL.md` (only the `name` and `description` keys; no YAML library needed). */
object SkillParser {
    data class Frontmatter(val name: String?, val description: String?)

    fun parse(text: String): Frontmatter {
        val lines = text.removePrefix("﻿").lines()
        if (lines.isEmpty() || lines[0].trim() != "---") return Frontmatter(null, null)
        var end = -1
        for (i in 1 until lines.size) if (lines[i].trim() == "---") { end = i; break }
        val body = if (end < 0) lines.drop(1) else lines.subList(1, end)
        var name: String? = null
        var desc: String? = null
        var i = 0
        while (i < body.size) {
            val line = body[i]
            // Only top-level keys (no indentation); nested blocks such as `metadata:` are skipped.
            val m = Regex("^(name|description)\\s*:\\s*(.*)$").find(line)
            if (m == null) { i++; continue }
            val key = m.groupValues[1]
            var value = m.groupValues[2].trim()
            if (value == "|" || value == ">" || value == "|-" || value == ">-" || value == "|+" || value == ">+") {
                // Block scalar: the following more-indented lines.
                val folded = value.startsWith(">")
                val parts = ArrayList<String>()
                var j = i + 1
                while (j < body.size && (body[j].isBlank() || body[j].startsWith(" ") || body[j].startsWith("\t"))) { parts += body[j].trim(); j++ }
                value = if (folded) parts.filter { it.isNotEmpty() }.joinToString(" ") else parts.joinToString("\n").trim()
                i = j
            } else {
                value = unquote(value)
                i++
            }
            if (key == "name") name = value else desc = value
        }
        return Frontmatter(name, desc)
    }

    private fun unquote(v: String): String {
        if (v.length >= 2 && v.first() == '"' && v.last() == '"') {
            return v.substring(1, v.length - 1).replace("\\\"", "\"").replace("\\\\", "\\").replace("\\n", "\n")
        }
        if (v.length >= 2 && v.first() == '\'' && v.last() == '\'') return v.substring(1, v.length - 1).replace("''", "'")
        // Unquoted scalar: a trailing " # comment" is not part of the value.
        val c = v.indexOf(" #")
        return (if (c >= 0) v.substring(0, c) else v).trim()
    }
}

/**
 * The template of a new skill. The front matter follows Hermes's own skills (name, description, version, author, license,
 * platforms, metadata.hermes) and its linter: the name is lowercase letters, digits, `-` and `_`, at most 64 characters, and
 * equals the folder name. The body is plain Markdown that the user then edits.
 */
object SkillTemplate {
    /** Folder names Hermes uses for a skill's supporting files: not allowed as a skill or category name. */
    val RESERVED_FOLDERS = setOf("references", "templates", "scripts", "assets")
    const val MAX_NAME = 64
    const val MAX_DESCRIPTION = 300
    private val NAME = Regex("[a-z0-9][a-z0-9_-]*")

    fun isValidName(name: String): Boolean = name.length in 1..MAX_NAME && NAME.matches(name)

    fun render(name: String, description: String): String {
        val desc = description.trim().ifEmpty { "Use when ... (say in one sentence when Hermes should use this skill)." }
        val quoted = "\"" + desc.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", " ") + "\""
        val title = name.split('-', '_').filter { it.isNotEmpty() }.joinToString(" ").replaceFirstChar { it.uppercase() }
        return """---
name: $name
description: $quoted
version: 1.0.0
author: You
license: MIT
platforms: [linux, macos, windows]
metadata:
  hermes:
    tags: [Custom]
    related_skills: []
---

# $title

Say in two or three sentences what this skill is for and what a good result looks like.

## When to use

- The situations in which Hermes should open this skill.
- What the user typically asks for.

## Steps

1. The first thing to do.
2. The next thing to do.
3. How to check that it worked.

## Notes

- Tools, files or commands this skill relies on.
- Mistakes to avoid.
"""
    }
}
